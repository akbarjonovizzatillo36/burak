// MASALAN: calculate("1 + 3"); return 4;
// 1 + 3 = 4, shu sababli 4 natijani qaytarmoqda.


function calculate(expression: string): number {
  const [a, b] = expression.split(" + ");
  return Number(a) + Number(b);
}
